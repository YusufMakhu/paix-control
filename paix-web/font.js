// Devuelve 5 columnas (cada una 7 bits, bit0=fila superior) para un carácter.
function glyphCols(ch){
  const g = FONT_ROWS[ch] || FONT_ROWS[' '];
  const cols=[];
  for(let x=0;x<5;x++){ let v=0; for(let y=0;y<7;y++){ if(g[y][x]==='1') v|=(1<<y); } cols.push(v); }
  return cols;
}

// Texto -> array de columnas (7 bits cada una), con 1 col de separación.
function textToCols(str){
  str = (str||'').toUpperCase().normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/Ñ/g,'N');
  const cols=[];
  for(const ch of str){
    const key = FONT_ROWS[ch] ? ch : ' ';
    for(const c of glyphCols(key)) cols.push(c);
    cols.push(0);
  }
  return cols;
}

// Ventana de 14 columnas del texto -> rows[14] (recortado al círculo).
function colsWindowToRows(cols, offset, topRow){
  topRow = (topRow==null) ? 4 : topRow;
  const rows = new Array(14).fill(0);
  for(let c=0;c<14;c++){
    const tc = offset + c;
    if(tc<0 || tc>=cols.length) continue;
    const cb = cols[tc];
    for(let y=0;y<7;y++){
      if((cb>>y)&1){ const r=topRow+y; if(r>=0&&r<14) rows[r] |= (1<<(13-c)); }
    }
  }
  for(let r=0;r<14;r++) rows[r] &= CIRCLE_MASK[r];
  return rows;
}

// Un carácter centrado en rows[14].
function charRows(ch, topRow, leftCol){
  topRow=(topRow==null)?4:topRow; leftCol=(leftCol==null)?5:leftCol;
  const cols=glyphCols(ch); const rows=new Array(14).fill(0);
  for(let x=0;x<5;x++){ const cb=cols[x]; for(let y=0;y<7;y++){ if((cb>>y)&1){ const c=leftCol+x, r=topRow+y; if(c>=0&&c<14&&r>=0&&r<14) rows[r]|=(1<<(13-c)); } } }
  for(let r=0;r<14;r++) rows[r]&=CIRCLE_MASK[r];
  return rows;
}
